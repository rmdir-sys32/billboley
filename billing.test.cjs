const assert=require('node:assert/strict');
const {applyCommand,total}=require('./dist/billing.js');
const basket=applyCommand('Do kilo chawal, aadha kilo chini, aur do doodh ke packet',[]);
assert.deepEqual(basket.map(r=>[r.id,r.qty]),[['rice',2000],['sugar',500],['milk',2000]]);
assert.equal(total(basket),19850);
assert.equal(total(applyCommand('दो किलो चावल और आधा किलो चीनी',[])),14250);
assert.equal(applyCommand('Chawal ek kilo kar do',basket)[0].qty,1000);
assert.equal(applyCommand('chini hata do',basket).length,2);
assert.equal(applyCommand('500 gram chawal',basket)[0].qty,2500);
assert.equal(applyCommand('ek litre doodh',[])[0].qty,2000);
assert.equal(applyCommand('250 ml tel',[])[0].qty,250);
assert.throws(()=>applyCommand('ek kilo basmati chawal',[]));
assert.throws(()=>applyCommand('ek kilo doodh',[]));
assert.throws(()=>applyCommand('aadha packet doodh',[]));
assert.throws(()=>applyCommand('0 kilo chawal',[]));
assert.throws(()=>applyCommand('ek kilo chawal, teen bananas',basket));
assert.throws(()=>applyCommand('tel ek litre kar do',basket));
assert.deepEqual(basket.map(r=>[r.id,r.qty]),[['rice',2000],['sugar',500],['milk',2000]]);
assert.equal(total(applyCommand('0.333 kilo chini',[])),1499);
console.log('16 billing checks passed: Hinglish, Hindi, totals, units, corrections, rejection, and atomic updates.');
